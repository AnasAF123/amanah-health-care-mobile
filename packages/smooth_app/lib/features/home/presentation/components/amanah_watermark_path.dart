class _AmanahWatermarkPainter extends CustomPainter {
  const _AmanahWatermarkPainter({this.gradient, this.color});

  final Gradient? gradient;
  final Color? color;

  @override
  void paint(Canvas canvas, Size size) {
    final Path path = AmanahWatermarkPathData.cachedPath;
    final double scale = size.width / 188.0;

    canvas.save();
    canvas.scale(scale, scale);

    final Paint paint = Paint()..style = PaintingStyle.fill;
    if (gradient != null) {
      paint.shader = gradient!.createShader(
        const Rect.fromLTWH(0, 0, 188, 188),
      );
    } else if (color != null) {
      paint.color = color!;
    } else {
      paint.color = const Color(0xFF0A44FF);
    }

    canvas.drawPath(path, paint);
    canvas.restore();
  }

  @override
  bool shouldRepaint(covariant _AmanahWatermarkPainter oldDelegate) {
    return oldDelegate.gradient != gradient || oldDelegate.color != color;
  }
}

class AmanahPixelTexture extends StatelessWidget {
  const AmanahPixelTexture({
    this.isDark,
    this.opacity = 0.35,
    this.maskType = AmanahPixelMaskType.fadeTop,
    super.key,
  });

  final bool? isDark;
  final double opacity;
  final AmanahPixelMaskType maskType;

  @override
  Widget build(BuildContext context) {
    final bool dark =
        isDark ?? (Theme.of(context).brightness == Brightness.dark);
    Widget content = CustomPaint(
      painter: AmanahOrganicPixelPainter(
        isDark: dark,
        opacity: opacity,
        fadeTop: maskType == AmanahPixelMaskType.fadeTop,
      ),
      size: Size.infinite,
    );

    if (maskType == AmanahPixelMaskType.concaveTop) {
      content = ShaderMask(
        shaderCallback: (Rect bounds) {
          return const RadialGradient(
            center: Alignment(0, -1.1),
            radius: 0.95,
            colors: <Color>[
              Colors.transparent,
              Colors.transparent,
              Color(0x40000000),
              Color(0xA6000000),
              Color(0xEB000000),
              Colors.black,
            ],
            stops: <double>[0.0, 0.38, 0.54, 0.74, 0.88, 1.0],
          ).createShader(bounds);
        },
        blendMode: BlendMode.dstIn,
        child: content,
      );
    } else if (maskType == AmanahPixelMaskType.bottomLeft) {
      content = ShaderMask(
        shaderCallback: (Rect bounds) {
          return const RadialGradient(
            center: Alignment.bottomLeft,
            radius: 1.25,
            colors: <Color>[
              Colors.black,
              Color(0xBF000000),
              Color(0x73000000),
              Color(0x33000000),
              Color(0x0F000000),
              Colors.transparent,
            ],
            stops: <double>[0.0, 0.15, 0.32, 0.50, 0.68, 0.85],
          ).createShader(bounds);
        },
        blendMode: BlendMode.dstIn,
        child: content,
      );
    } else if (maskType == AmanahPixelMaskType.topRight ||
        maskType == AmanahPixelMaskType.bottomRight) {
      content = ShaderMask(
        shaderCallback: (Rect bounds) {
          final Alignment center = maskType == AmanahPixelMaskType.topRight
              ? const Alignment(1.05, -1.0)
              : const Alignment(1.05, 1.0);

          return RadialGradient(
            center: center,
            radius: 1.15,
            colors: const <Color>[
              Colors.black,
              Colors.black,
              Color(0xCC000000),
              Color(0x80000000),
              Color(0x2B000000),
              Colors.transparent,
            ],
            stops: const <double>[0.0, 0.22, 0.45, 0.68, 0.88, 1.0],
          ).createShader(bounds);
        },
        blendMode: BlendMode.dstIn,
        child: content,
      );
    } else if (maskType == AmanahPixelMaskType.horizontalEdges) {
      content = ShaderMask(
        shaderCallback: (Rect bounds) {
          return const LinearGradient(
            begin: Alignment.centerLeft,
            end: Alignment.centerRight,
            colors: <Color>[
              Colors.black,
              Color(0xD9000000),
              Color(0x59000000),
              Colors.transparent,
              Colors.transparent,
              Color(0x59000000),
              Color(0xD9000000),
              Colors.black,
            ],
            stops: <double>[0.0, 0.10, 0.24, 0.40, 0.60, 0.76, 0.90, 1.0],
          ).createShader(bounds);
        },
        blendMode: BlendMode.dstIn,
        child: content,
      );
    }

    return Positioned.fill(child: content);
  }
}

enum AmanahPixelMaskType {
  none,
  fadeTop,
  concaveTop,
  bottomLeft,
  topRight,
  bottomRight,
  horizontalEdges,
}

class AmanahOrganicPixelPainter extends CustomPainter {
  const AmanahOrganicPixelPainter({
    required this.isDark,
    this.fadeTop = false,
    this.opacity = 0.35,
  });

  final bool isDark;
  final bool fadeTop;
  final double opacity;

  static double _seededHash(double x, double y, double seed) {
    final double n =
        math.sin(x * 12.9898 + y * 78.233 + seed * 37.719) * 43758.5453;
    return n - n.floorToDouble();
  }

  static void drawPixelsToCanvas(
    Canvas canvas,
    Size size, {
    bool isDark = false,
    double opacity = 0.35,
    bool fadeTop = true,
  }) {
    const double pixelSize = 4.0;
    const double gap = 1.8;
    const double step = pixelSize + gap;
    final int cols = (size.width / step).ceil() + 1;
    final int rows = (size.height / step).ceil() + 1;
    const double dropoutThreshold = 0.36;

    final List<Color> customColors = isDark
        ? const <Color>[
            Color(0xFF2563EB),
            Color(0xFF3B82F6),
            Color(0xFF0A44FF),
            Color(0xFF60A5FA),
            Color(0xFF93C5FD),
          ]
        : const <Color>[
            Color(0xFF0A44FF),
            Color(0xFF2563EB),
            Color(0xFF60A5FA),
            Color(0xFF93C5FD),
            Color(0xFFBFDBFE),
          ];

    final Paint paint = Paint()..style = PaintingStyle.fill;

    for (int r = 0; r < rows; r++) {
      final double yRatio = r / rows;
      // Progressive bottom-to-top gradual fade matching web maskGradient
      final double verticalFade = fadeTop
          ? (yRatio * yRatio * 1.15).clamp(0.0, 1.0)
          : 1.0;

      if (fadeTop && verticalFade < 0.04) {
        continue;
      }

      for (int c = 0; c < cols; c++) {
        final double dropoutVal = _seededHash(r.toDouble(), c.toDouble(), 11);
        if (dropoutVal < dropoutThreshold) {
          continue;
        }

        final double opacRand = _seededHash(r.toDouble(), c.toDouble(), 23);
        final double cellOpacity =
            (0.28 + opacRand * 0.72).clamp(0.12, 1.0) * opacity * verticalFade;

        if (cellOpacity < 0.02) {
          continue;
        }

        final double sizeRand = _seededHash(r.toDouble(), c.toDouble(), 37);
        final double curSize = sizeRand < 0.20
            ? pixelSize * 0.75
            : (sizeRand > 0.85 ? pixelSize * 1.15 : pixelSize);
        final double offset = (pixelSize - curSize) / 2.0;

        final double colorRand = _seededHash(r.toDouble(), c.toDouble(), 47);
        final int colorIdx =
            (colorRand * customColors.length).floor() % customColors.length;
        final Color baseColor = customColors[colorIdx];

        paint.color = baseColor.withValues(alpha: cellOpacity);

        final double px = c * step + offset;
        final double py = r * step + offset;

        if (px > size.width || py > size.height) {
          continue;
        }

        canvas.drawRRect(
          RRect.fromRectAndRadius(
            Rect.fromLTWH(px, py, curSize, curSize),
            const Radius.circular(1.0),
          ),
          paint,
        );
      }
    }
  }

  @override
  void paint(Canvas canvas, Size size) {
    drawPixelsToCanvas(
      canvas,
      size,
      isDark: isDark,
      opacity: opacity,
      fadeTop: fadeTop,
    );
  }

  @override
  bool shouldRepaint(covariant AmanahOrganicPixelPainter oldDelegate) {
    return oldDelegate.isDark != isDark ||
        oldDelegate.fadeTop != fadeTop ||
        oldDelegate.opacity != opacity;
  }
}
